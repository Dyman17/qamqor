"""Regenerates assets/icons.js from the Lucide SVG files in assets/icons/ (ISC licence, see icons/LICENSE).
Why: opening index.html from disk (file://) cannot fetch() SVG files, and <img> cannot take currentColor,
so the inner paths are inlined once into icons.js. Run: python -I build-icons.py
"""
import json
import pathlib
import re

here = pathlib.Path(__file__).resolve().parent
out = {}
for f in sorted((here / "icons").glob("*.svg")):
    body = re.search(r"<svg[^>]*>(.*)</svg>", f.read_text(encoding="utf-8"), re.S).group(1)
    out[f.stem] = re.sub(r"\s+", " ", body).strip()
(here / "icons.js").write_text(
    "/* GENERATED by build-icons.py from assets/icons/*.svg (Lucide, ISC). Do not edit by hand. */\n"
    "window.ICONS = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n",
    encoding="utf-8",
)
print(len(out), "icons")
