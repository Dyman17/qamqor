"""Regenerates assets/icons.js from the SVG files in assets/icons/ (Phosphor, MIT; Tabler, MIT; licences in icons/).
Why: file:// cannot fetch() SVG files and <img> cannot take currentColor, so the paths are inlined once.
Keys: "regular/name", "fill/name" (Phosphor, 256 viewBox, fill) and "tabler/name" (24 viewBox, stroke 1.5 here).
Run: python -I build-icons.py"""
import json, pathlib, re
here = pathlib.Path(__file__).resolve().parent
out = {}
for group in ("regular", "fill", "tabler"):
    for f in sorted((here / "icons" / group).glob("*.svg")):
        txt = f.read_text(encoding="utf-8")
        vb = re.search(r'viewBox="([^"]+)"', txt).group(1)
        body = re.search(r"<svg[^>]*>(.*)</svg>", txt, re.S).group(1)
        body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
        out[group + "/" + f.stem] = {"vb": vb, "d": re.sub(r"\s+", " ", body).strip()}
(here / "icons.js").write_text(
    "/* GENERATED by build-icons.py from assets/icons (Phosphor MIT, Tabler MIT). Do not edit by hand. */\n"
    "window.ICONS = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
print(len(out), "icons")
